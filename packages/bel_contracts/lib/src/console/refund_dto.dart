    required this.bookingRef,
    required this.amount,
    required this.stationId,
  });

  final String id;
  final String bookingRef;
  final Money amount;
  final String stationId;

  factory ClaimedRefundDto.fromJson(Map<String, Object?> json) =>
      ClaimedRefundDto(
        id: Wire.requireString(json['id'], 'id'),
        bookingRef: Wire.requireString(json['bookingRef'], 'bookingRef'),
        amount: Wire.readMoney(json['amount'], field: 'amount'),
        stationId: Wire.requireString(json['stationId'], 'stationId'),
      );
}
